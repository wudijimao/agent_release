import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const stylesPath = path.join(packageRoot, 'src', 'styles.css');
const outputPath = path.join(packageRoot, 'src', 'generated', 'antdTheme.ts');
const checkOnly = process.argv.includes('--check');

const styles = fs.readFileSync(stylesPath, 'utf8');
const tokenMappings = [
  ['colorPrimary', '--chatui-color-brand-primary'],
  ['colorPrimaryHover', '--chatui-color-brand-primary-hover'],
];

const readToken = (tokenName) => {
  const escapedName = tokenName.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const match = styles.match(new RegExp(`^\\s*${escapedName}\\s*:\\s*([^;]+);`, 'm'));
  if (!match?.[1]?.trim()) throw new Error(`Missing theme token ${tokenName} in src/styles.css`);
  return match[1].trim();
};

const entries = tokenMappings.map(([propertyName, tokenName]) => (
  `  ${propertyName}: '${readToken(tokenName)}',`
));
const generated = [
  '// Generated by scripts/generate-antd-theme.mjs from src/styles.css.',
  '// Do not edit this file directly.',
  'export const chatUIAntdSeedToken = {',
  ...entries,
  '} as const;',
  '',
].join('\n');

if (checkOnly) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
  if (current !== generated) {
    console.error('Generated Ant Design theme is stale. Run npm run theme:generate.');
    process.exit(1);
  }
  console.log('Generated Ant Design theme matches src/styles.css.');
} else {
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, 'utf8') !== generated) {
    fs.writeFileSync(outputPath, generated);
  }
}
